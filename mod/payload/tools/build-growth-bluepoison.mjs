// Growth-only maintainer addition. Official data and asset pipelines; no generated data/*.json is edited.
// Character reference: https://prts.wiki/w/%E8%93%9D%E6%AF%92 (2026-10-25).
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {localOfficialUnits} from '../server/plugins/officialUnits.js';
import {composeUnitRecord,statusKey} from '../shared/standIn.js';
import {getData} from '../server/data.js';
import {buildPlan} from './assets/plan.mjs';
import {Downloader} from './assets/downloader.mjs';
import {collectLeaves,downloadLeaves,resolveTemplate} from './assets/manifest.mjs';
import {processModels} from './assets/spine.mjs';
import {ensureOfficialTables} from './assets/official-tables.mjs';
import {cachedJson} from './assets/cache.mjs';
import {RAW} from './assets/sources.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),charId='char_129_bluep';
const normal='chess_char_2_30_a',elite='chess_char_2_30_b',data=getData();
if(data.chess[normal]||data.chess[elite])throw Error('Growth Blue Poison ID is already used by native data');
const statuses=[data.chess.chess_char_2_07_a.status,data.chess.chess_char_2_07_b.status];
await ensureOfficialTables(root,'growth Blue Poison addition',{log:line=>console.log(line)},[charId]);
const {unit,version}=localOfficialUnits(path.join(root,'data'))(charId,statuses),chess={};
for(const [i,id]of [normal,elite].entries()) {
  const source=data.chess[i?'chess_char_2_07_b':'chess_char_2_07_a'];
  const form=unit.forms[statusKey(statuses[i])],moduleId=form.modules?.[0]?.uniEquipId ?? null;
  const identity={...source,chessId:id,baseId:normal,goldenId:elite,upgradeChessId:i?null:elite,
    backup:null,bonds:['egirShip'],garrisonIds:[],shopSortId:30,identifier:230};
  const record=composeUnitRecord(identity,unit,form,{skillIndex:1,moduleId});
  if(!record?.skill||record.charId!==charId)throw Error('Cannot derive official Blue Poison form');
  chess[id]={...record,growthOperator:true};
}
const roster={name:'蓝毒',id:normal,tier:2,main:'阿戈尔',addon:'无',row:null,handler:'deathSpread',traitChanged:true,tierChanged:false,
  normal:'<被击倒时>使已激活的【阿戈尔】临时层数+4，使1名友方【阿戈尔】干员获得该特质\n本干员可以部署在地面上',
  elite:'<被击倒时>使已激活的【阿戈尔】临时层数+8，使1名友方【阿戈尔】干员获得该特质\n本干员可以部署在地面上'};
await fs.writeFile(path.join(root,'shared/growthBluePoison.js'),
  `// Growth-only Blue Poison; official source fingerprint ${version}.\n// Generated by tools/build-growth-bluepoison.mjs; PRTS character reference, maintainer's tier/bonds/trait.\n// i18n-ignore-file: game data, not interface messages.\nexport const GROWTH_BLUE_POISON=${JSON.stringify({chess,roster},null,2)};\n`);
console.log(JSON.stringify({charId,forms:Object.keys(chess),version}));
if(!process.argv.includes('--no-assets')) {
  const charword=await cachedJson({cacheFile:path.join(root,'.cache/gamedata/excel/charword_table.json'),url:RAW.gamedata+'excel/charword_table.json',maxBytes:40000000});
  const audio={unitBanks:new Map(),skillBanks:new Map(),bank:()=>[],bgm:()=>null};
  const plan=buildPlan({assets07:{},ops03:{chess:[{charId,defaultSkillIndex:1}]},enemies05:{},maps05:{},modelsData:{},audio,charword,voiceJp:true,optionalVoice:true,
    extraOperators:{[charId]:{...unit,skills:chess[normal].skills}}});
  const template={chars:plan.template.chars,skills:plan.template.skills,audio:Object.fromEntries(Object.entries(plan.template.audio).filter(([key])=>key.startsWith('voice')))};
  const models=new Map([...plan.models].filter(([key])=>key.startsWith(`op:${charId}:`)));
  const cache=path.join(root,'.cache/bluepoison-assets'),assetRoot=path.join(root,'public/assets/growth-bluepoison');
  await fs.mkdir(cache,{recursive:true});
  const dl=new Downloader({root:assetRoot,ledgerPath:path.join(cache,'ledger.json'),concurrency:4,timeoutMs:30000,retries:2});await dl.loadLedger();
  await downloadLeaves(collectLeaves(template),dl,assetRoot,'Blue Poison art');
  const spine=await processModels(models,{root:assetRoot,dl,cachePath:path.join(cache,'spine-cache.json')});
  const resolved=resolveTemplate(template,{root:assetRoot,spine:spine.entries ?? spine.spine ?? spine});
  const prefix=v=>Array.isArray(v)?v.map(prefix):v&&typeof v==='object'?Object.fromEntries(Object.entries(v).map(([k,x])=>[k,prefix(x)]))
    :typeof v==='string'&&v.startsWith('/assets/')?v.replace('/assets/','/assets/growth-bluepoison/'):v;
  if(!resolved.value.chars?.[charId]?.spine?.front||!resolved.value.chars?.[charId]?.spine?.back)throw Error('Both Blue Poison Spine facings are required');
  for(const tree of ['voice','voiceJp'])for(const slot of ['start','faceEnemy','select','place','skill1','skill2','skill3','skill4','resultFour','resultThree','resultTwo','resultLose']){
    if(!resolved.value.audio?.[tree]?.[charId]?.[slot])throw Error(`Missing Blue Poison ${tree}/${slot}`);
  }
  await fs.writeFile(path.join(root,'shared/growthBluePoisonAssets.js'),
    `// Parsed from Blue Poison's actual Front/Back skeletons; binary game art stays in ignored public/assets.\nexport const GROWTH_BLUE_POISON_ASSETS=${JSON.stringify(prefix(resolved.value),null,2)};\n`);
  await dl.saveLedger();console.log(JSON.stringify({assets:'ready',misses:resolved.misses}));
}
